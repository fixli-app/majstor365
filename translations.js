  let currentLanguage = "bs";

  function getText(key) {
    return translations[currentLanguage][key] || translations.bs[key] || key;
  }

  function setLanguage(language) {
    if (!Object.prototype.hasOwnProperty.call(translations, language)) return;

    currentLanguage = language;
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      element.innerHTML = getText(element.dataset.i18n);
    });

    document.querySelectorAll("[data-i18n-content]").forEach((element) => {
      element.setAttribute("content", getText(element.dataset.i18nContent));
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      element.setAttribute("placeholder", getText(element.dataset.i18nPlaceholder));
    });

    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
      element.setAttribute("aria-label", getText(element.dataset.i18nAriaLabel));
    });

    document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
      element.setAttribute("alt", getText(element.dataset.i18nAlt));
    });

    document.querySelectorAll("[data-i18n-title]").forEach((element) => {
      element.setAttribute("title", getText(element.dataset.i18nTitle));
    });

    document.querySelectorAll("[data-language]").forEach((button) => {
      button.setAttribute("aria-pressed", String(button.dataset.language === language));
    });

    const menuToggle = document.querySelector(".menu-toggle");
    if (menuToggle) {
      const menuIsOpen = menuToggle.getAttribute("aria-expanded") === "true";
      menuToggle.setAttribute("aria-label", getText(menuIsOpen ? "aria.closeMenu" : "aria.openMenu"));
    }
  }

  document.querySelectorAll("[data-language]").forEach((button) => {
    button.addEventListener("click", () => {
      setLanguage(button.dataset.language);

      const menuToggle = document.querySelector(".menu-toggle");
      if (menuToggle && menuToggle.getAttribute("aria-expanded") === "true") {
        menuToggle.click();
      }
    });
  });

  window.majstorI18n = {
    get currentLanguage() {
      return currentLanguage;
    },
    getText,
    hasTranslation(key, language = currentLanguage) {
      return Object.prototype.hasOwnProperty.call(translations[language], key);
    },
    setLanguage
  };

